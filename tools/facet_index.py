RULING_HDR = re.compile(r"^## Ruling (\d+)\b(.*)$")
ADDENDA_HDR = re.compile(r"^## Post-ingest addenda\s*(\d*)\b(.*)$")
AMEND_HDR = re.compile(r"^> ### (?:⚠\s*)?Amendment (\d+) \((.*)$")

# MEASURED, not assumed: across all five ruling documents the lettered marker is
# `**<n><letter> <dash>` — letter, SPACE, dash — 151 times out of 152. The single
# exception is not a sub-ruling at all but a CLOSURE marker naming the sub-ruling
# it closes (`**18g-CLOSED (Director, 2026-08-06): "Keep ivory, judge on asset."`),
# and it carries the Director's own sentence. A dash class that tolerates a bare
# hyphen swallows it into 18g and loses one of the two holdings. So the space is
# required, and the suffixed form gets its own pattern and its own row.
SUB_RULING = re.compile(r"^\*\*(\d+)([a-z])\s+" + DASH)
SUB_CLOSURE = re.compile(r"^\*\*(\d+)([a-z])-([A-Z][A-Z-]+)\b")
HANDOFF_HDR = re.compile(r"^## Session handoff\s*(\d*)\s*\((.*)$")
SECTION_HDR = re.compile(r"^(#{2,3}) +(.*)$")

# correction / supersession verbs, directed at a numbered ruling. Conservative by
# design: a phrase this does not match is under-counted, never mis-attributed.
SUPERSEDE_RE = re.compile(
    r"(?:Ruling|Amendment)\s+(\d+[a-z]?)(?:'s [^.;:]{0,60}?)?\s+"
    r"(?:is\s+|are\s+)?(?:now\s+)?"
    r"(?:CORRECTED|corrected|WITHDRAWN|withdrawn|SUPERSEDED|superseded|VOID|void)\b"
)
SUPERSEDE_TITLE_RE = re.compile(
    r"\b(\d+[a-z]?)\s+(?:is\s+)?(?:corrected in place|CORRECTED IN PLACE|withdrawn|WITHDRAWN)"
)


def parse_rulings():
    """Numbered rulings, their lettered sub-rulings, amendments and addenda."""
    rows = []
    for arc, rel in NUMBERED_RULING_FILES:
        rows.extend(_parse_numbered(arc, rel, RULING_HDR, "ruling", "Ruling"))
        rows.extend(_parse_numbered(arc, rel, ADDENDA_HDR, "addendum", "Post-ingest addenda"))
    for arc, rel in AMENDMENT_FILES:
        rows.extend(_parse_amendments(arc, rel))
    rows.sort(key=lambda r: (r["arc"], r["sort_num"], r["sort_letter"], r["kind"]))
    return rows


def _header_blocks(ls, pattern):
    """Yield (match, header_line_no, body_lines) for every header match."""
    hits = [(i, pattern.match(ln)) for i, ln in enumerate(ls)]
    hits = [(i, m) for i, m in hits if m]
    for k, (i, m) in enumerate(hits):
        end = hits[k + 1][0] if k + 1 < len(hits) else len(ls)
        # a later `## ` header of another kind also terminates the block
        for j in range(i + 1, end):
            if ls[j].startswith("## "):
                end = j
                break
        yield m, i, ls[i + 1:end]


def _parse_numbered(arc, rel, pattern, kind, label):
    out = []
    ls = lines_of(rel)
    for m, i, body in _header_blocks(ls, pattern):
        num = m.group(1)
        if not num:
            num = "1"          # E11's first addendum carries no digit
        tail = m.group(2)
        title = re.sub(r"^\s*" + DASH + r"\s*", "", tail).strip()
        title = re.sub(r"^\(([^)]*)\)\s*" + DASH + r"\s*", "", title).strip()
        anchor = "%s %s" % (label, num)
        subs = _parse_subs(arc, rel, num, kind, body, i + 1, find_date(m.group(0)))
        # A parent's body must NOT re-index its sub-rulings' prose: every sub is its
        # own row, so including their text made Ruling 4 a 3,932-character document
        # that competes with its own five children and dilutes bm25's length
        # normalisation for both. The parent keeps only what belongs to it.
        own = _minus_sub_paragraphs(body, i + 1, subs)
        row = dict(
            arc=arc, number=num, parent=None, kind=kind,
            date=find_date(m.group(0)) or find_date("\n".join(body[:6])),
            holding=one_line(strip_md(title)) or one_line(strip_md(tail)),
            body=strip_md(own),
            file=rel, anchor=anchor, locator=ls[i].rstrip(), line=i + 1,
            sort_num=int(num), sort_letter="",
        )
        out.append(row)
        out.extend(subs)
    return out


def _minus_sub_paragraphs(body, body_start, subs):
    """The parent's own prose: the block minus every paragraph a sub-ruling owns."""
    owned = set()
    for s in subs:
        first = s["line"] - 1 - body_start
        n = len(s["body"].split("\n"))
        for k in range(first, first + n + 1):
            owned.add(k)
    return "\n".join(ln for k, ln in enumerate(body) if k not in owned)


SKIPPED_CROSSREFS = []


def _parse_subs(arc, rel, parent_num, parent_kind, body, body_start, parent_date):
    """Lettered sub-rulings — and closure markers — inside one ruling's body."""
    out = []
    pars = paragraphs(body, body_start)
    for start, par in pars:
        first = par[0]
        m = SUB_RULING.match(first)
        closure = None if m else SUB_CLOSURE.match(first)
        if not m and not closure:
            continue
        g = m or closure
        num, letter = g.group(1), g.group(2)
        if num != parent_num:
            # a lettered marker numbered for a DIFFERENT ruling is a cross-reference
            # opening a paragraph, not this ruling's own sub-ruling. Skipped, and
            # recorded so the report can quote how often it happens.
            SKIPPED_CROSSREFS.append((rel, start + 1, first[:70]))
            continue
        title, rest = bold_lead_title(par)
        if title is None:
            continue
        if closure:
            suffix = "-" + g.group(3)
            number = num + letter + suffix
            anchor = "Ruling %s%s%s" % (num, letter, suffix)
            locator = "**%s%s%s" % (num, letter, suffix)
            kind = "sub-%s-closure" % parent_kind
            title = re.sub(r"^\d+[a-z]-[A-Z-]+\s*:?\s*", "", title)
        else:
            number = num + letter
            anchor = "Ruling %s%s" % (num, letter)
            locator = "**%s%s " % (num, letter)
            kind = "sub-" + parent_kind
            title = re.sub(r"^\d+[a-z]\s*" + DASH + r"\s*", "", title)
        out.append(dict(
            arc=arc, number=number, parent=num, kind=kind,
            date=find_date(g.group(0)) or find_date(title) or parent_date,
            holding=one_line(strip_md(title)),
            body=strip_md("\n".join(par)),
            file=rel, anchor=anchor, locator=locator, line=start + 1,
            sort_num=int(num), sort_letter=letter,
        ))
    return out


def _parse_amendments(arc, rel):
    out = []
    ls = lines_of(rel)
    for m, i, body in _header_blocks(ls, AMEND_HDR):
        num = m.group(1)
        tail = m.group(2)
        author = tail.split(")")[0]
        title = tail.split(")", 1)[1] if ")" in tail else tail
        title = re.sub(r"^\s*" + DASH + r"\s*", "", title).strip()
        out.append(dict(
            arc=arc, number="A" + num, parent=None, kind="amendment",
            date=find_date(author),
            holding=one_line(strip_md(title)),
            body=strip_md("\n".join(body)),
            file=rel, anchor="Amendment %s" % num,
            locator="Amendment %s (" % num, line=i + 1,
            sort_num=int(num), sort_letter="",
        ))
    return out


# The record announces its verdicts in capitals and names its authority in the
# header. Both are ontology this index was missing: without them, the ruling that IS
# an acceptance is indistinguishable from the three that merely discuss one, and
# "when was the pair accepted" ranks the discussion above the event. Ordered most-
# to least specific; the first hit in the holding wins.
VERDICTS = [
    "ACCEPTED", "REJECTED", "RATIFIED", "WITHDRAWN", "FALSIFIED", "CONFIRMED",
    "DESIGNATED", "DIRECTED", "ADOPTED", "SUSPENDED", "RELEASED", "CLOSED",
    "CLEARED", "HALTED", "BANKED", "MINTED", "VOID", "RULED",
]


def classify(holding):
    """(verdict, authority) for a ruling, from the record's own capitalised marks.

    THE CAPITALS ARE THE CONVENTION AND MUST NOT BE NORMALISED AWAY. A verdict is
    what a ruling DOES, and the record shouts it: `THE PAIR IS ACCEPTED`,
    `the pair is REJECTED`, `is RATIFIED end to end`, `GATE 1: ACCEPTED`. The same
    word in lower case is an adjective describing an artifact — `D9's wine has no
    cluster on the accepted pair` is not an acceptance. An earlier version of this
    function upper-cased the holding first and so marked three rulings ACCEPTED that
    accept nothing, which put two of them above the actual acceptance in the ranking.
    Match case-sensitively.
    """
    verdict = None
    for v in VERDICTS:
        if re.search(r"\b%s\b" % v, holding):
            verdict = v
            break
    authority = "Director" if re.search(r"\bDirector\b", holding) else "advisor"
    return verdict, authority


def link_supersessions(rulings):
    """Populate supersedes / superseded_by from EXPLICIT correction verbs only.

    A lower bound by construction: the record also corrects by narrative ("the
    word stands, anchored by…"), which no pattern reads without guessing. The
    report states the coverage rather than implying completeness.
    """
    by_key = {}
    for r in rulings:
        by_key[(r["arc"], r["number"])] = r
        r["supersedes"] = []
        r["superseded_by"] = []
    for r in rulings:
        hay = r["holding"] + " \n " + r["body"][:4000]
        targets = set(SUPERSEDE_RE.findall(hay)) | set(SUPERSEDE_TITLE_RE.findall(r["holding"]))
        for t in sorted(targets):
            if t == r["number"]:
                continue
            tgt = by_key.get((r["arc"], t))
            if tgt is None:
                continue
            if t not in r["supersedes"]:
                r["supersedes"].append(t)
            if r["number"] not in tgt["superseded_by"]:
                tgt["superseded_by"].append(r["number"])
    for r in rulings:
        r["supersedes"] = ",".join(sorted(r["supersedes"])) or None
        r["superseded_by"] = ",".join(sorted(r["superseded_by"])) or None


NUM_RULE = re.compile(r"^(\d+)\. +\*\*")
LIST_ITEM = re.compile(r"^(?:\d+\.|[-*]) +")
PAID_RE = re.compile(r"\b(E0[1-9]|E1[0-5])\b")


LIST_LAW = re.compile(r"^(?:\d+\.|[-*]) +\*\*")


def list_items(par):
    """Split a paragraph wherever a list item OPENS IN BOLD — the law shape.

    Two properties of CLAUDE.md make a plain blank-line splitter lose most of the
    corpus, and both were measured rather than assumed:

      * lists carry NO blank line between items, so ten numbered role rules read as
        one block and only the first is captured (2 of 10 before this existed, with
        the four `Judging artifacts` and eight `Standing technical constraints`
        bullets absent entirely);
      * an item may itself CONTAIN a blank line — advisor rule 3 runs to two
        paragraphs — after which items 4 and 5 sit in a block that no longer starts
        with a marker, and were lost even once list splitting existed.

    So the split is on the marker-plus-bold pattern anywhere in the block, not on the
    block's first line. Requiring the `**` immediately after the marker keeps prose
    that merely begins a line with `- ` from being cut into phantom laws.
    """
    if not any(LIST_LAW.match(ln) for ln in par):
        return [par]
    out, cur = [], []
    for ln in par:
        if LIST_LAW.match(ln) and cur:
            out.append(cur)
            cur = [ln]
        else:
            cur.append(ln)
    if cur:
        out.append(cur)
    return out


def parse_laws():
    """The CLAUDE.md law corpus.

    Three forms, all the file's own: bold-lead paragraphs (`**An inherited claim
    is…**`), numbered role rules (`1. **Never judge…**`) and bulleted constraints
    (`- **Weld before decimating.**`). A law must open its paragraph OR its list
    item — which is what keeps a wrapped mid-sentence `**word**` (CLAUDE.md:141) out
    of the table, while still reaching the items inside a blank-line-free list.
    """
    rows = []
    for rel in LAW_FILES:
        ls = lines_of(rel)
        heads = [(i, ln) for i, ln in enumerate(ls) if ln.startswith("## ")]
        bounds = []
        for k, (i, ln) in enumerate(heads):
            end = heads[k + 1][0] if k + 1 < len(heads) else len(ls)
            bounds.append((ln[3:].strip(), i, end))
        for section, s, e in bounds:
            for start, block in paragraphs(ls[s + 1:e], s + 1):
                offset = 0
                for par in list_items(block):
                    line = start + offset
                    offset += len(par)
                    first = par[0]
                    title, kind = None, None
                    if BOLD_LEAD.match(first):
                        title, _ = bold_lead_title(par)
                        kind = "law"
                    elif LIST_ITEM.match(first):
                        inner = "\n".join(par).split("**", 2)
                        # the bold must open the item: anything between the marker
                        # and the `**` means the bold is mid-sentence, not a statement
                        if len(inner) >= 3 and not LIST_ITEM.sub("", inner[0]).strip():
                            title = inner[1]
                            kind = "rule" if NUM_RULE.match(first) else "law"
                    if title is None:
                        continue
                    stmt = one_line(strip_md(title))
                    if len(stmt) < 12:
                        continue
                    body = strip_md("\n".join(par))
                    paid = sorted(set(PAID_RE.findall(body)))
                    rows.append(dict(
                        statement=stmt, kind=kind, section=section,
                        paid_for_by=",".join(paid) or None, body=body, file=rel,
                        anchor="%s · %s" % (section, stmt[:60]),
                        locator=first.rstrip(), line=line + 1,
                    ))
    return rows


EXP_ROW = re.compile(r"^\| \[?(E\d\d)\]?(?:\([^)]*\))? \| (.*?) \| (.*?) \|\s*$")


def parse_experiments():
    """E01…, from the experiments README table, supplemented by the filesystem.

    The table is the authored source; it is also STALE by construction (E13/E14/E15
    have no row, E12's row says "Rulings 1-8"). Experiments present on disk but
    absent from the table enter with status `not in the README table` — a reported
    finding, never a silent fill.
    """
    rows = {}
    rel = "docs/experiments/README.md"
    for ln in lines_of(rel):
        m = EXP_ROW.match(ln)
        if not m:
            continue
        eid, question, status = m.group(1), m.group(2), m.group(3)
        rows[eid] = dict(
            id=eid, question=one_line(strip_md(question), 400),
            status=one_line(strip_md(status), 400),
            verdict=_verdict(status), spec_file=None, report_file=None,
            body=strip_md(question + " " + status),
            file=rel, anchor="the experiment table · %s" % eid,
            locator="| [%s]" % eid, line=0,
        )
    # locate each experiment's own files, and discover experiments the table omits
    # .md first, then the rest, each alphabetically — so an experiment discovered
    # from disk is anchored at a document's heading rather than at a JSON's `{`.
    files = sorted(
        (f for f in os.listdir(os.path.join(REPO, "docs/experiments"))
         if re.match(r"^E\d\d[-.]", f)),
        key=lambda f: (0 if f.endswith(".md") else 1, f))
    for f in files:
        eid = f[:3]
        r = rows.get(eid)
        if r is None:
            # E13/E14/E15 have no README-table row. They enter from disk, pointed at
            # their own document's first heading — a locator findable IN that file,
            # rather than the filename, which is not text inside it. The missing
            # table row is a reported finding; this parser does not write one.
            rel_f = "docs/experiments/" + f
            head, head_line = _first_heading(rel_f)
            r = rows[eid] = dict(
                id=eid, question=None,
                status="not in the README table",
                verdict=None, spec_file=None, report_file=None, body="",
                file=rel_f,
                anchor="files on disk · %s" % eid,
                locator=head, line=head_line,
            )
        rp = "docs/experiments/" + f
        if r["spec_file"] is None and re.search(r"(kickoff|spec|-E\d|-the-|-cover-|-paint-|-cull-|-atlas-|-facial-|-texture-|-environment-|-dense-|-context-)", f):
            r["spec_file"] = rp
        if r["report_file"] is None and "report" in f:
            r["report_file"] = rp
    for eid, r in rows.items():
        if r["locator"] == "| [%s]" % eid and r["line"] == 0:
            for i, ln in enumerate(lines_of(rel)):
                if ln.startswith("| [%s]" % eid) or ln.startswith("| %s " % eid):
                    r["line"] = i + 1
                    r["locator"] = ln[:40].rstrip()
                    break
    return [rows[k] for k in sorted(rows)]


def _first_heading(rel):
    """First `#` heading of a file, and its 1-based line. Falls back to line 1."""
    ls = lines_of(rel)
    for i, ln in enumerate(ls):
        if ln.startswith("#"):
            return ln.rstrip(), i + 1
    for i, ln in enumerate(ls):
        if ln.strip():
            return ln.rstrip()[:60], i + 1
    return "", 1


def _verdict(status):
    s = status.upper()
    for word in ("ACCEPTED", "RULED", "IN FLIGHT", "RUN AND RULED", "STAGED", "CLOSED"):
        if word in s:
            return word
    return None


def parse_handoffs():
    """Executor dispatches and halts, arc-scoped because the numbers collide.

    E04's first handoff carries no number at all (`## Session handoff (2026-08-04,
    evening) — … SUPERSEDED`). It is recorded as number `1` with its unnumbered form
    kept in the locator, because dropping a real dispatch to satisfy a regex would
    lose a row the count check is entitled to see.
    """
    rows = []
    for arc, rel in HANDOFF_FILES:
        ls = lines_of(rel)
        for m, i, body in _header_blocks(ls, HANDOFF_HDR):
            num = m.group(1) or "1"
            tail = m.group(2)
            date = find_date(tail)
            title = tail.split(")", 1)[1] if ")" in tail else tail
            title = re.sub(r"^\s*" + DASH + r"\s*", "", title).strip()
            txt = "\n".join(body)
            rows.append(dict(
                arc=arc, number=int(num), date=date,
                outcome=one_line(strip_md(title), 300),
                commits=",".join(sorted(set(re.findall(r"`([0-9a-f]{7,40})`", txt)))) or None,
                superseded=1 if "SUPERSEDED" in ls[i] else 0,
                body=strip_md(txt),
                file=rel, anchor="Session handoff %s (%s)" % (num, arc),
                locator=ls[i].rstrip()[:60], line=i + 1,
            ))
    rows.sort(key=lambda r: (r["arc"], r["number"]))
    return rows


def parse_decisions():
    """An INDEX over the profiles' registry. The profile stays canonical.

    Only `{value, why, from}` entries are indexed — the shape `subject_profile.bind`
    enforces. Keys beginning `_` are the profiles' own meta/marker convention and are
    recorded as status markers rather than as decided values.
    """
    rows = []
    for rel in PROFILE_FILES:
        prof = json.loads(read(rel))
        subject = prof.get("name") or os.path.basename(rel)
        text = read(rel).split("\n")
        # `_still_suspended` is where undecidedness actually lives — and each entry
        # opens with its own disposition (RESOLVED / RULED / DECIDED / CONVERTED /
        # PARTIALLY SUPERSEDED / DERIVED, AWAITING …), so the block is a history of
        # what was suspended and how it closed. Indexed under the pseudo-tool
        # `_still_suspended` so a session can ask what a subject still owes.
        for key in sorted(prof.get("_still_suspended", {})):
            note = str(prof["_still_suspended"][key])
            rows.append(dict(
                subject=subject, tool="_still_suspended", key=key,
                value=one_line(note, 200), status=_decision_status(note),
                ruling=None, why=one_line(note, 400),
                body=strip_md("%s %s" % (key, note)),
                file=rel, anchor="%s · _still_suspended · %s" % (subject, key),
                locator='"%s"' % key, line=_line_of(text, '"%s"' % key),
            ))
        for tool in sorted(prof.get("tools", {})):
            block = prof["tools"][tool]
            for key in sorted(block):
                ent = block[key]
                if key.startswith("_"):
                    rows.append(dict(
                        subject=subject, tool=tool, key=key,
                        value=one_line(str(ent), 200), status="marker",
                        ruling=None, why=None,
                        body=strip_md("%s %s" % (key, ent)),
                        file=rel, anchor="%s · %s · %s" % (subject, tool, key),
                        locator='"%s"' % key, line=_line_of(text, '"%s"' % key),
                    ))
                    continue
                if not isinstance(ent, dict) or "value" not in ent:
                    continue
                why = ent.get("why", "")
                rows.append(dict(
                    subject=subject, tool=tool, key=key,
                    value=one_line(json.dumps(ent["value"], ensure_ascii=False), 200),
                    status=_decision_status(why),
                    ruling=ent.get("from"),
                    why=one_line(why, 400),
                    body=strip_md("%s %s %s %s" % (key, ent["value"], why, ent.get("from", ""))),
                    file=rel, anchor="%s · %s · %s" % (subject, tool, key),
                    locator='"%s"' % key, line=_line_of(text, '"%s"' % key),
                ))
    return rows


CLASS_LABEL = re.compile(r"^([A-Z][A-Z0-9 /_-]{3,44})(?=[:,.(—-]|\s+-\s)")


def _decision_status(why):
    """The entry's class, read ONLY from a capitalised label at the head of `why`.

    That leading label is the profiles' own convention — `FIRST-RUN OPERATING POINT
    at the accepted route's value`, `PROTECTIVE TRANSCRIPTION (the E04 Ruling 22
    class)`, `SPENT, WITH A BYTE ANCHOR`. Anywhere ELSE in the prose the same words
    are narrative about the past, and reading them as status inverts their meaning:
    an earlier version scanned the whole string and so labelled three entries
    UNDECIDED whose `why` says *"the arc's one deliberately undecided value"* (ruled
    0.005 by E12 Ruling 25c) and *"Found undecided by Ruling 25's sweep, then
    anchored"*. An index that reports a decided value as undecided is a second
    authority contradicting the record, which is the one thing this design forbids.

    An entry that carries a `value` at all is DECIDED by the loader's own semantics —
    `subject_profile.bind` applies it to the tool. Undecidedness lives in the
    `_still_suspended` block and the `_`-prefixed markers, both indexed separately.
    """
    m = CLASS_LABEL.match(why.strip())
    if m:
        label = m.group(1).strip()
        if len(label.split()) <= 6:
            return label
    return "decided"


def _line_of(text_lines, needle):
    for i, ln in enumerate(text_lines):
        if needle in ln:
            return i + 1
    return 0


# The record writes Windows paths with BACKSLASHES (`facet_E02\out\atlas_final.png`)
# and shell fragments with variable prefixes (`"$j\inpainted.png"`). Both are matched;
# `$` and `%` are excluded from the lookbehind so a variable prefix is not swallowed
# into the path (which would mint a phantom artifact called `j/inpainted.png`).
ARTIFACT_RE = re.compile(
    r"(?<![\w/\\.$%-])((?:[A-Za-z0-9_][A-Za-z0-9_.\-]*[/\\])*[A-Za-z0-9_][A-Za-z0-9_.\-]*"
    r"\.(?:glb|png|npy|jsonl|json|obj|ply|ps1|sh))(?![\w])"
)
STATUS_WORDS = [
    ("ACCEPTED", r"\bACCEPTED\b"),
    ("REJECTED", r"\bREJECTED\b"),
    ("SUPERSEDED", r"\bSUPERSEDED\b|\bsuperseded\b"),
    ("WITHDRAWN", r"\bWITHDRAWN\b|\bwithdrawn\b"),
    ("FROZEN", r"\bfrozen as canon\b|\bFROZEN\b"),
]
# extensions that are the record's own instruments/inputs rather than artifacts
ARTIFACT_KIND = {
    "glb": "mesh", "png": "render", "npy": "array", "json": "data",
    "jsonl": "log", "obj": "mesh", "ply": "mesh", "ps1": "script", "sh": "script",
}


def parse_artifacts(ruling_index):
    """Meshes, renders, sidecars and sheets, extracted by path shape.

    THE RECORD HAS NO CONVENTION FOR THESE. They are paths in prose. So this is
    extraction, not parsing: every path-shaped token in the markdown record becomes a
    row carrying where it is mentioned, how often, and — only where a status word
    stands in the same paragraph — a status. Absent that, status is NULL rather than
    guessed. `provenance_ruling` is the nearest preceding ruling anchor in the same
    file, which is a locality heuristic and is labelled as one.
    """
    seen = {}
    for rel in record_markdown():
        ls = lines_of(rel)
        pars = paragraphs(ls, 0)
        for start, par in pars:
            text = "\n".join(par)
            status = None
            for name, pat in STATUS_WORDS:
                if re.search(pat, text):
                    status = name
                    break
            for m in ARTIFACT_RE.finditer(text):
                raw = m.group(1)
                # the KEY is separator-normalised, because `facet_E02\out\x.png` and
                # `facet_E02/out/x.png` are one artifact; the LOCATOR stays raw,
                # because the pointer gate looks for it in the file as written.
                tok = raw.replace("\\", "/")
                if tok.count(".") and tok.split(".")[-1] not in ARTIFACT_KIND:
                    continue
                rec = seen.get(tok)
                if rec is None:
                    rec = seen[tok] = dict(
                        path=tok, kind=ARTIFACT_KIND[tok.split(".")[-1]],
                        status=status, mentions=0,
                        provenance_ruling=_nearest_ruling(ruling_index, rel, start + 1),
                        body="", file=rel, anchor="first mentioned in %s" % rel,
                        locator=raw, line=start + 1,
                    )
                rec["mentions"] += 1
                if rec["status"] is None and status is not None:
                    rec["status"] = status
                if len(rec["body"]) < 1200:
                    rec["body"] = (rec["body"] + " " + one_line(strip_md(text), 400)).strip()
    return [seen[k] for k in sorted(seen)]


def _nearest_ruling(ruling_index, rel, line):
    best = None
    for r in ruling_index:
        if r["file"] != rel or r["line"] > line:
            continue
        if best is None or r["line"] > best["line"]:
            best = r
    return best["anchor"] if best else None


# the record's own naming verbs. A phenomenon in this repo is minted out loud.
PHENOM_PATTERNS = [
    ("banked as a measured phenomenon", r"is BANKED as a measured phenomenon"),
    ("minted", r"IS MINTED|is MINTED"),
    ("named forward", r"IS NAMED FORWARD"),
    ("named", r"\bis NAMED\b|\bIS NAMED\b|\bis named:|\bclass is named\b"),
    ("ledger form", r"the ledger takes the form, named"),
    ("new law", r"a new law for the record"),
    ("banked as", r"\bis BANKED as\b|\bis banked as (?:a|the|this)\b"),
]


def parse_phenomena(rulings):
    """The named measured effects.

    ALSO CONVENTIONLESS, and named with at least seven different verbs. This reads
    the verbs the record actually uses and reports what that catches. A phenomenon
    named without one of them is invisible here, and that is the honest boundary of
    the table rather than a bug to paper over with a hand-kept list — a hand-kept
    list is exactly what the design forbids.
    """
    rows = []
    for r in rulings:
        text = r["holding"] + "\n" + r["body"]
        hit = None
        for name, pat in PHENOM_PATTERNS:
            if re.search(pat, text):
                hit = name
                break
        if hit is None:
            continue
        rows.append(dict(
            name=one_line(r["holding"], 140),
            marker=hit,
            statement=one_line(r["holding"], 300),
            instances=r["arc"],
            body=r["body"][:4000],
            file=r["file"], anchor=r["anchor"], locator=r["locator"], line=r["line"],
        ))
    rows.sort(key=lambda x: (x["file"], x["line"]))
    return rows


def parse_prose():
    """Every prose section of the record that no structured table already owns.

    The reports, predictions, halts, specs and kickoffs are where the MEASUREMENTS
    live — a ruling cites them, and a session that can find the ruling but not the
    evidence has half an index. So the whole `docs/experiments/` markdown corpus is
    sectioned by heading here, alongside README, the handbook and the design docs.

    Sections a structured table already owns are skipped so a holding is not indexed
    twice under two identities: `## Ruling N`, `## Post-ingest addenda N` and
    `## Session handoff N` blocks belong to `rulings` and `handoffs`. The E08
    amendments sit inside a blockquote under `## 3.`, so that document is excluded
    from prose wholesale and reached through its amendment rows.
    """
    owned_hdr = (RULING_HDR, ADDENDA_HDR, HANDOFF_HDR)
    structured = {rel for _, rel in NUMBERED_RULING_FILES}
    structured |= {rel for _, rel in AMENDMENT_FILES}
    files = list(PROSE_FILES)
    files += [rel for _, rel in TOPICAL_RULING_FILES]
    files += [rel for _, rel in HANDOFF_FILES]
    files += [f for f in record_markdown()
              if f.startswith("docs/experiments/") and f not in files]
    rows = []
    for rel in sorted(set(files)):
        if rel in structured:
            continue
        ls = lines_of(rel)
        heads = [(i, m) for i, m in ((i, SECTION_HDR.match(ln)) for i, ln in enumerate(ls)) if m]
        if not heads:
            # a document with no `##` heading is still evidence; index it whole
            body = strip_md("\n".join(ls))
            if len(body.strip()) < 40:
                continue
            head, hl = _first_heading(rel)
            rows.append(dict(title=one_line(strip_md(head).lstrip("# "), 200),
                             body=body, file=rel, anchor="(whole document)",
                             locator=head, line=hl))
            continue
        # a `##` block owned by a structured table owns its `###` children too —
        # otherwise a handoff's task list is indexed twice, once as part of the
        # handoff row and once on its own, and the two compete in the ranking.
        owned_spans = []
        h2 = [i for i, _ in heads if ls[i].startswith("## ")]
        for k, i in enumerate(h2):
            if any(h.match(ls[i]) for h in owned_hdr):
                owned_spans.append((i, h2[k + 1] if k + 1 < len(h2) else len(ls)))

        def is_owned(line_no):
            return any(a <= line_no < b for a, b in owned_spans)

        # the preamble above the first `##` carries the document's own thesis
        pre = strip_md("\n".join(ls[:heads[0][0]]))
        if len(pre.strip()) >= 40:
            head, hl = _first_heading(rel)
            rows.append(dict(title=one_line(strip_md(head).lstrip("# "), 200),
                             body=pre, file=rel, anchor="(preamble)",
                             locator=head, line=hl))
        for k, (i, m) in enumerate(heads):
            end = heads[k + 1][0] if k + 1 < len(heads) else len(ls)
            if is_owned(i):
                continue
            title = strip_md(m.group(2)).strip()
            body = strip_md("\n".join(ls[i + 1:end]))
            if len(body.strip()) < 40:
                continue
            rows.append(dict(
                title=one_line(title, 200), body=body,
                file=rel, anchor=title[:80], locator=ls[i].rstrip()[:70], line=i + 1,
            ))
    rows.sort(key=lambda r: (r["file"], r["line"]))
    return rows


