def _grep_count(rel, pattern):
    rx = re.compile(pattern)
    return sum(1 for ln in lines_of(rel) if rx.match(ln))


def _sequence_numbers(con, arc, kind):
    rows = con.execute(
        "SELECT number FROM rulings WHERE arc=? AND kind=?", (arc, kind)).fetchall()
    have = set()
    for (n,) in rows:
        m = re.match(r"^A?(\d+)$", n)
        if m:
            have.add(int(m.group(1)))
    return sorted(have)


def _sequence_gaps(con, arc, kind, lo, hi):
    return sorted(set(range(lo, hi + 1)) - set(_sequence_numbers(con, arc, kind)))


# Ordinary English function words. Measured on this corpus BEFORE they were removed:
# "the" appears in 94.9% of indexed rows, "is" in 77.9%, "not" in 62.2%. An OR query
# carrying them matches nearly everything, and the discriminating term ("galleon",
# 10.0%; "mix", 1.7%) is then one weak signal among many. This list is generic — it
# is not derived from any question in the seeded set.
STOPWORDS = frozenset("""
a an and are as at be been but by can did do does for from had has have how i if in
into is it its of on or our so than that the their them then there these they this
to was we were what when where which who why will with would you your not no nor
""".split())

CANDIDATES = 400          # re-ranking window; fixed, so `q` is deterministic

# Exact-phrase hits are a BEST-BET SLOT, not a takeover. Uncapped, a phrase that
# happens to appear in a pointer document monopolises the page: this repo's own
# dispatch quotes every seeded question verbatim, so `q "the fifth brush signature"`
# returned three documents that merely POINT at Ruling 27d ahead of the ruling — the
# ruling says "fifth signature", not "fifth brush signature", so it is not a phrase
# match at all. Three slots keeps the exact match's priority and leaves the rest of
# the page to relevance.
PHRASE_SLOTS = 3


def fts_terms(phrase):
    """Content words of a query phrase, lowercased, stopwords dropped."""
    words = [w.lower() for w in re.findall(r"[A-Za-z0-9_][A-Za-z0-9_.'-]*", phrase)
             if len(w) > 1]
    kept = [w for w in words if w not in STOPWORDS]
    return kept or words          # never return an empty query


def fts_or(phrase):
    return " OR ".join('"%s"' % w for w in fts_terms(phrase))


