#!/usr/bin/env python
"""facet_index — the derived index over the markdown record.

WHAT THIS IS. `docs/index/facet.db` is a SQLite+FTS5 map of this repo's record,
GENERATED by this file and never hand-edited. The markdown stays canonical:
corrections in place, prose holdings, the evidence trail. The database exists so a
session can *query* instead of reading, and then read the forty lines the query
pointed at rather than the six hundred it would have skimmed. The design ruling is
docs/context-architecture.md.

THE DAY IT IS HAND-EDITED IT IS WRONG BY DEFINITION. Every fold regenerates it;
`verify` gates the regeneration; a build that fails verify does not commit.

THIS FILE NEVER WRITES TO THE RECORD. It parses by the record's own conventions and
reports what it could not parse. A builder that "fixes" a source document while
parsing it has failed — malformed-by-convention text is a report item, never an edit.

WHAT IT PARSES, AND WHERE THE CONVENTIONS COME FROM. Nothing here was invented; each
pattern is the shape the record already uses:

  ## Ruling 25 — TITLE (2026-08-07)          numbered rulings   E04/E10/E11/E12/E10off
  **25c — TITLE.** body...                   lettered subs      E12 mostly, E04/E10off
  > ### Amendment 32 (advisor, 2026-08-04)   amendments         E08
  ## Post-ingest addenda 3 (2026-08-07, …)   addenda            E11
  ## Session handoff 15 (2026-08-07) — …     handoffs           E04/E12 kickoffs
  **A law's statement.** what it was paid…   laws               CLAUDE.md
  tools.<tool>.<key> = {value, why, from}    decisions          profiles/*.json

DETERMINISM IS A CONTRACT, NOT AN ASPIRATION. Two builds from an unchanged record
must be byte-identical. Everything that could vary is pinned: the file list is an
explicit sorted constant, every traversal is `sorted()`, every insert order is fixed,
the whole build is ONE transaction, and no timestamp or random value is ever written.
`verify` tests this rather than trusting it, with a pre-registered `.dump` fallback
if SQLite's own file header (a change counter, an implementation detail) defeats byte
equality.

ANCHORS COME IN TWO FORMS AND THAT IS DELIBERATE. `anchor` is the human label a
session reads and cites ("Ruling 25c"). `locator` is the exact string findable in the
file ("**25c —"), because GitHub mints anchors for `#`-headings only and a bold lead
is not one. The dangling-pointer gate checks `locator`; the query output prints
`anchor`.

Standards compliance
  PIN_PER_STEP        the DB is a pure function of the record at a commit; this file
                      is committed beside it; `build` takes no tuning parameters.
  ANDON_AUTHORITY     `verify` exits non-zero on any of four legs and prints the
                      failing evidence; a parse it cannot do is reported, never
                      papered over.
  NAMED_COMPENSATORS  writes exactly one path (docs/index/facet.db); undo is deleting
                      it. The record is opened read-only.
  DECOMPOSE_BY_SECRETS the parser knows conventions, the schema knows ontology, the
                      verifier knows neither's internals — it re-derives its counts
                      from the record with its own greps.
  UNCERTAINTY_GATED_HUMANS parse limitations print as findings for the advisor's eye.
  EXTERNAL_VERIFIER   the seeded question set is advisory-authored and its expected
                      answers are keyed to record anchors this file never reads as
                      input; counts are checked against independent greps.
"""
