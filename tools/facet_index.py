def query(con, phrase, limit=8):
    """Two-stage retrieval: exact phrase first, then bm25 scaled by term coverage.

    Why not bm25 alone: the record repeats its vocabulary across four arcs — every
    subject's mix discussion says "reference brush dilation" — so a disjunction ranks
    a row matching a few common terms alongside one matching every term. The target
    is usually the row that matches every term (measured 4/4, 6/6 and 7/7 on three
    seeded questions), so a row missing terms is penalised in proportion.

    Why coverage SCALES bm25 rather than overriding it: overriding was tried and
    FALSIFIED — coordination level as the primary sort key scored 9/14 against
    bm25's 12/14, because it discards length normalisation and long prose sections
    trivially contain every term. Ranking by title-coverage first was also tried and
    scored 11/14. Scaling keeps bm25's length normalisation and reached 13/14. Every
    variant is a generic retrieval mechanism; none knows about a specific document,
    and no seeded question was altered to fit any of them.
    """
    # `disp` is returned for display; `title || body` is returned for coverage
    # scoring. bm25 weights name the INDEXED columns only: title, then body.
    sql = ("SELECT file, anchor, disp, line, tbl, "
           "bm25(fts, 8.0, 1.0) AS r, title || ' ' || body "
           "FROM fts WHERE fts MATCH ? ORDER BY r, file, line LIMIT ?")
    out, seen = [], set()

    # STAGE 1 — the exact adjacent phrase, over the FULL word run with stopwords
    # KEPT, because a phrase is adjacency and dropping "the"/"is" breaks it. This is
    # what makes a quoted holding find its own ruling: `THE PAIR IS ACCEPTED` is
    # Ruling 14's title verbatim, while a bag of {pair, accepted} cannot separate the
    # acceptance from three rulings that merely mention an accepted artifact — the
    # acceptance loses on length alone (body 2,084 chars against 221, with the
    # HIGHEST term frequency in the corpus). Measured: this stage is the difference
    # between 13/14 and 14/14 on the seeded set.
    words = [w.lower() for w in re.findall(r"[A-Za-z0-9_][A-Za-z0-9_.'-]*", phrase)
             if len(w) > 1]
    if len(words) > 1:
        try:
            for f, a, t, line, tbl, r, _ in con.execute(
                    sql, ('"%s"' % " ".join(words), PHRASE_SLOTS)).fetchall():
                if (f, a) not in seen:
                    seen.add((f, a))
                    out.append((f, a, t, line, tbl, r))
        except sqlite3.OperationalError:
            pass

    # STAGE 2 — relaxed: content words OR'd, bm25 scaled by term coverage
    ts = fts_terms(phrase)
    try:
        rows = con.execute(
            sql, (" OR ".join('"%s"' % w for w in ts), CANDIDATES)).fetchall()
    except sqlite3.OperationalError:
        return out[:limit]
    scored = []
    for f, a, t, line, tbl, r, hay in rows:
        low = hay.lower()
        cover = sum(1 for w in ts if w in low)
        # bm25 is negative-better; scaling a negative score by a fraction < 1 moves
        # it toward zero, i.e. demotes it. Floor at one term so a row never scores 0.
        scored.append((r * (max(cover, 1) / float(len(ts))), f, line,
                       (f, a, t, line, tbl, r)))
    scored.sort(key=lambda s: (s[0], s[1], s[2]))
    for row in (s[3] for s in scored):
        if (row[0], row[1]) not in seen:
            seen.add((row[0], row[1]))
            out.append(row)
    return out[:limit]


def verify(db_path, top_n=3):
    fails = []
    print("=" * 78)
    print("facet_index verify — four legs")
    print("=" * 78)

    # ---- leg 1: determinism -------------------------------------------------
    print("\n[leg 1] determinism — two builds from an unchanged record")
    tmp_a = db_path + ".det_a"
    tmp_b = db_path + ".det_b"
    build(tmp_a, quiet=True)
    build(tmp_b, quiet=True)
    with open(tmp_a, "rb") as fh:
        ba = fh.read()
    with open(tmp_b, "rb") as fh:
        bb = fh.read()
    if ba == bb:
        print("  BYTE-IDENTICAL   %d bytes, both builds" % len(ba))
        det_leg = "byte-identity"
    else:
        da = "\n".join(sqlite3.connect(tmp_a).iterdump())
        db_ = "\n".join(sqlite3.connect(tmp_b).iterdump())
        if da == db_:
            first = next((i for i in range(min(len(ba), len(bb))) if ba[i] != bb[i]), -1)
            print("  byte-identity FAILED (first differing offset %d of %d/%d bytes)"
                  % (first, len(ba), len(bb)))
            print("  .DUMP-IDENTICAL  %d chars — logical determinism holds"
                  % len(da))
            det_leg = ".dump-identity (pre-registered fallback)"
        else:
            print("  FAIL — neither byte- nor .dump-identical")
            fails.append("determinism: two builds differ logically")
            det_leg = "NEITHER"
    for p in (tmp_a, tmp_b):
        if os.path.exists(p):
            os.remove(p)

    con = sqlite3.connect(db_path)

    # ---- leg 2: counts against the record's own numbering --------------------
    print("\n[leg 2] counts — the verifier's own grep against the DB")
    for name, rel, pattern, table, where in COUNT_CHECKS:
        g = _grep_count(rel, pattern)
        d = con.execute("SELECT COUNT(*) FROM %s WHERE %s" % (table, where)).fetchone()[0]
        ok = (g == d)
        print("  %-28s grep %4d   db %4d   %s" % (name, g, d, "ok" if ok else "MISMATCH"))
        if not ok:
            fails.append("count %s: grep %d != db %d" % (name, g, d))

    # Ranges as DISPATCHED, not as measured. They are pre-registered bounds and are
    # left exactly where they were written; anything the record carries ABOVE a
    # dispatched bound prints below as a completeness note rather than silently
    # widening the gate. (E04 turns out to carry a Ruling 29 — the dispatch and the
    # experiments README both say 28. That is a finding about the prose, and the
    # advisor rules on it; this gate does not re-derive itself around it.)
    seq = [("E12", "ruling", 1, 28), ("E04", "ruling", 1, 28),
           ("E08", "amendment", 1, 35), ("E11", "ruling", 1, 7),
           ("E10", "ruling", 1, 12)]
    for arc, kind, lo, hi in seq:
        gaps = _sequence_gaps(con, arc, kind, lo, hi)
        print("  %-28s %s %d-%d gaps: %s"
              % (arc + " sequence", kind, lo, hi, gaps if gaps else "none"))
        if gaps:
            fails.append("%s %s sequence gaps %s" % (arc, kind, gaps))
        above = [n for n in _sequence_numbers(con, arc, kind) if n > hi]
        if above:
            # States ONLY what it measured. An earlier version added "<- record
            # carries more than the prose claims", which was true when written and
            # false eight hours later: E15 Ruling 5 corrected E04's count to 29 at
            # three sites, and the line went on asserting the prose was stale. A
            # verifier that editorialises about a document it does not read will
            # eventually lie to every session that runs it.
            print("  %-28s ABOVE the dispatched bound of %d: %s  <- measured; the "
                  "bound stays as dispatched (E15 Ruling 3c)"
                  % ("  ↑ completeness", hi, above))

    hg = sorted(r[0] for r in con.execute(
        "SELECT number FROM handoffs WHERE arc='E12'").fetchall())
    missing = sorted(set(range(1, 17)) - set(hg))
    print("  %-28s present %s   missing %s"
          % ("E12 handoffs 1-16", hg, missing if missing else "none"))
    if missing != [1]:
        fails.append("E12 handoff coverage unexpected: missing %s" % missing)

    exp = sorted(r[0] for r in con.execute("SELECT id FROM experiments").fetchall())
    want = ["E%02d" % i for i in range(1, 16)]
    miss = [e for e in want if e not in exp]
    print("  %-28s have %d, missing %s" % ("experiments E01-E15", len(exp),
                                           miss if miss else "none"))
    if miss:
        fails.append("experiments missing %s" % miss)

    # ---- leg 3: zero dangling pointers ---------------------------------------
    print("\n[leg 3] pointers — every row's file exists and its locator is findable")
    cache = {}
    dangling = 0
    checked = 0
    for table in ("rulings", "laws", "experiments", "handoffs",
                  "artifacts", "phenomena", "decisions"):
        rows = con.execute("SELECT file, anchor, locator FROM %s" % table).fetchall()
        bad = 0
        for f, a, loc in rows:
            checked += 1
            if f not in cache:
                p = os.path.join(REPO, f)
                cache[f] = read(f) if os.path.exists(p) else None
            src = cache[f]
            if src is None or loc not in src:
                bad += 1
        dangling += bad
        print("  %-12s %5d rows   dangling %d" % (table, len(rows), bad))
        if bad:
            fails.append("%s: %d dangling pointers" % (table, bad))
    fts_bad = 0
    for f, loc in con.execute("SELECT file, locator FROM fts").fetchall():
        if f not in cache:
            p = os.path.join(REPO, f)
            cache[f] = read(f) if os.path.exists(p) else None
        if cache[f] is None or loc not in cache[f]:
            fts_bad += 1
    print("  %-12s %5d rows   dangling %d"
          % ("fts", con.execute("SELECT COUNT(*) FROM fts").fetchone()[0], fts_bad))
    if fts_bad:
        fails.append("fts: %d dangling pointers" % fts_bad)
    print("  total checked %d, dangling %d" % (checked, dangling + fts_bad))

    # ---- leg 4: the seeded question set --------------------------------------
    print("\n[leg 4] the seeded question set — target within the top %d" % top_n)
    hits = 0
    for question, phrase, want in SEEDED:
        targets = want if isinstance(want, list) else [want]
        rows = query(con, phrase, limit=top_n)
        got = None
        for rank, (f, a, t, line, tbl, r) in enumerate(rows, 1):
            if any(f == wf and (wa is None or a == wa) for wf, wa in targets):
                got = rank
                break
        ok = got is not None
        hits += 1 if ok else 0
        tgt = " | ".join("%s · %s" % (wf, wa or "(any anchor)") for wf, wa in targets)
        print("  %-34s %-8s %s" % (question[:34], "rank %d" % got if ok else "MISS", tgt))
        if not ok:
            for rank, (f, a, t, line, tbl, r) in enumerate(rows, 1):
                print("        got %d. %s:%s [%s]" % (rank, f, a, tbl))
            fails.append("seeded question MISS: %s" % question)
    print("  %d / %d" % (hits, len(SEEDED)))

    print("\n" + "=" * 78)
    print("determinism leg that held: %s" % det_leg)
    if fails:
        print("VERIFY FAILED — %d" % len(fails))
        for f in fails:
            print("  ✗ %s" % f)
        return 1
    print("VERIFY PASSED — all four legs")
    return 0


