def main(argv=None):
    ap = argparse.ArgumentParser(
        description="the derived SQLite+FTS5 index over the facet record")
    ap.add_argument("verb", choices=["build", "verify", "q", "claims"])
    ap.add_argument("term", nargs="?", default=None, help="query term for `q`")
    ap.add_argument("--db", default=os.path.join(REPO, DB_REL))
    ap.add_argument("--limit", type=int, default=8)
    ap.add_argument("--table", default=None, help="restrict `q` to one table")
    args = ap.parse_args(argv)

    if args.verb == "build":
        build(args.db)
        return 0
    if args.verb == "verify":
        return verify(args.db)
    if args.verb == "claims":
        return claims(args.db)
    if not args.term:
        print("q needs a term", file=sys.stderr)
        return 2
    con = sqlite3.connect(args.db)
    rows = query(con, args.term, limit=args.limit * 6)
    n = 0
    for f, a, disp, line, tbl, r in rows:
        if args.table and tbl != args.table:
            continue
        # the dispatch's contract: file:anchor · one-line holding
        head = "%s:%d" % (f, line)
        print("%-52s %s" % (head, a))
        if disp and disp.strip() and disp.strip() != a.strip():
            print("%-52s   · %s" % ("", one_line(disp, 150)))
        n += 1
        if n >= args.limit:
            break
    if n == 0:
        print("(no rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
